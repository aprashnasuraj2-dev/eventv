import assert from 'node:assert/strict';import {assess,secondsOf,clock} from '../assets/boston-marathon-2027.js';
const base={age:35,category:'men',time:'2:54:00',drop:0,date:'2026-05-01',certified:true,applied:true};
const check=x=>assess({...base,...x});
assert.equal(secondsOf('2:54:00'),10440);assert.equal(clock(317),'00:05:17');
assert.equal(check({}).standard,10800);assert.equal(check({}).competitive,true);
assert.equal(check({time:'2:54:43'}).competitive,true);assert.equal(check({time:'2:54:44'}).competitive,false);
assert.equal(check({time:'2:55:00'}).meets,true);assert.equal(check({time:'2:55:00'}).randomPossible,true);
assert.equal(check({time:'3:00:00'}).meets,true);assert.equal(check({time:'3:00:01'}).meets,false);
assert.equal(check({time:'2:50:00',drop:1500}).adjustment,300);
assert.equal(check({time:'2:50:00',drop:1499}).adjustment,0);
assert.equal(check({time:'2:45:00',drop:3000}).indexed,10500);
assert.equal(check({time:'2:45:00',drop:5999}).adjustment,600);
assert.equal(check({time:'2:30:00',drop:6000}).meets,false);
assert.equal(check({date:'2025-09-12'}).meets,false);
assert.equal(check({date:'2025-09-13'}).meets,true);
assert.equal(check({date:'2026-09-19'}).meets,false);
assert.equal(check({certified:false}).meets,false);
assert.equal(check({applied:false,time:'2:55:00'}).randomPossible,false);
assert.equal(check({age:34}).standard,10500);assert.equal(check({age:35}).standard,10800);
assert.equal(check({age:80,category:'nonbinary'}).standard,19200);
for(const x of [{age:17},{age:''},{drop:-1},{drop:''},{drop:1500.5},{time:'bad'},{date:'2026-02-30'},{category:'wheelchair'}])assert.throws(()=>check(x));
console.log('Boston 2027 eligibility boundary tests passed');
// Adversarial parsing and acceptance-counterexample checks.
for(const bad of ['2:60:00','2:59:60','0:59:59','13:00:00','2:5:00','2:54:00x'])assert.throws(()=>secondsOf(bad));
for(const bad of ['2026-13-01','2026-00-01','2026-02-29','not-a-date'])assert.throws(()=>check({date:bad}));
assert.equal(check({time:'2:54:43',applied:false}).competitive,true,'Cutoff screening must not imply a submitted application');
assert.equal(check({time:'2:54:44',applied:true}).randomPossible,true,'One second beyond cutoff is not competitively accepted');
assert.equal(check({time:'2:55:00',applied:false}).randomPossible,false,'No submitted application means no random-selection consideration');
assert.equal(check({drop:2999}).adjustment,300);
assert.equal(check({drop:3000}).adjustment,600);
assert.equal(check({drop:5999}).adjustment,600);
assert.equal(check({drop:6000}).adjustment,null);
